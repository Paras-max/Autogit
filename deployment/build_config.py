"""
deployment/build_config.py – PyInstaller build specification for AutoGit AI

Usage:
    python deployment/build_config.py          # writes autogit_ai.spec then runs PyInstaller
    pyinstaller autogit_ai.spec                # rebuild from existing spec
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

# ─── Paths ────────────────────────────────────────────────────────────────────
ROOT = Path(__file__).parent.parent.resolve()
DIST_DIR = ROOT / "dist"
BUILD_DIR = ROOT / "build"
SPEC_FILE = ROOT / "autogit_ai.spec"
FRONTEND_DIST = ROOT / "frontend" / "dist"

APP_NAME = "AutoGit-AI"
ICON_PATH = ROOT / "frontend" / "public" / "favicon.ico"  # optional


# ─── Spec content ─────────────────────────────────────────────────────────────

SPEC_TEMPLATE = '''# -*- mode: python ; coding: utf-8 -*-
# AutoGit AI – PyInstaller spec (auto-generated by deployment/build_config.py)

import sys
from pathlib import Path

ROOT = Path(r"{root}")

a = Analysis(
    [str(ROOT / "main.py")],
    pathex=[str(ROOT)],
    binaries=[],
    datas=[
        # Include frontend build artefacts
        (str(ROOT / "frontend" / "dist"), "frontend/dist"),
        # Include .env.example for first-run setup guidance
        (str(ROOT / ".env.example"), "."),
        # Include logs directory placeholder
        (str(ROOT / "logs"), "logs"),
    ],
    hiddenimports=[
        "uvicorn.logging",
        "uvicorn.loops",
        "uvicorn.loops.auto",
        "uvicorn.protocols",
        "uvicorn.protocols.http",
        "uvicorn.protocols.http.auto",
        "uvicorn.protocols.websockets",
        "uvicorn.protocols.websockets.auto",
        "uvicorn.lifespan",
        "uvicorn.lifespan.on",
        "fastapi",
        "pydantic",
        "sqlalchemy",
        "git",
        "watchdog",
        "httpx",
        "aiofiles",
        "dotenv",
    ],
    hookspath=[],
    hooksconfig={{}},
    runtime_hooks=[],
    excludes=[],
    noarchive=False,
)

pyz = PYZ(a.pure, a.zipped_data, cipher=None)

exe = EXE(
    pyz,
    a.scripts,
    [],
    exclude_binaries=True,
    name="{app_name}",
    debug=False,
    bootloader_ignore_signals=False,
    strip=False,
    upx=True,
    console=True,
    icon={icon},
)

coll = COLLECT(
    exe,
    a.binaries,
    a.zipfiles,
    a.datas,
    strip=False,
    upx=True,
    upx_exclude=[],
    name="{app_name}",
)
'''


def write_spec() -> Path:
    icon_value = f'r"{ICON_PATH}"' if ICON_PATH.exists() else "None"
    content = SPEC_TEMPLATE.format(
        root=str(ROOT),
        app_name=APP_NAME,
        icon=icon_value,
    )
    SPEC_FILE.write_text(content, encoding="utf-8")
    print(f"[build] Wrote spec → {SPEC_FILE}")
    return SPEC_FILE


def build_frontend() -> None:
    """Run npm build if frontend/dist doesn't exist or is stale."""
    pkg = ROOT / "frontend" / "package.json"
    if not pkg.exists():
        print("[build] No frontend/package.json found – skipping frontend build.")
        return
    print("[build] Building frontend …")
    subprocess.run(["npm", "run", "build"], cwd=ROOT / "frontend", check=True, shell=True)


def run_pyinstaller(spec: Path) -> None:
    print("[build] Running PyInstaller …")
    subprocess.run(
        [sys.executable, "-m", "PyInstaller", str(spec), "--noconfirm"],
        cwd=ROOT,
        check=True,
    )
    print(f"[build] ✓ Build complete → {DIST_DIR / APP_NAME}")


def create_windows_launcher() -> None:
    """Write a slim launcher .bat next to the .exe for end users."""
    launcher = DIST_DIR / APP_NAME / "Launch_AutoGit_AI.bat"
    launcher.write_text(
        f'@echo off\nstart "" "%~dp0{APP_NAME}.exe"\n',
        encoding="utf-8",
    )
    print(f"[build] Wrote launcher → {launcher}")


def main() -> None:
    print(f"[build] Project root: {ROOT}")

    # 1. Build frontend
    if not FRONTEND_DIST.exists():
        build_frontend()
    else:
        print(f"[build] Using existing frontend/dist ({len(list(FRONTEND_DIST.rglob('*')))} files)")

    # 2. Write spec
    spec = write_spec()

    # 3. Run PyInstaller
    run_pyinstaller(spec)

    # 4. Windows helper launcher
    if sys.platform == "win32":
        create_windows_launcher()

    print("\n[build] ✅ AutoGit AI packaged successfully.")
    print(f"        Distribution: {DIST_DIR / APP_NAME}")


if __name__ == "__main__":
    main()
